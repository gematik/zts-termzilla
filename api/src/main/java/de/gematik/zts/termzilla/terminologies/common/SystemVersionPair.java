package de.gematik.zts.termzilla.terminologies.common;

import java.util.Optional;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.Setter;

@Getter
@Setter
@Builder
@AllArgsConstructor
public class SystemVersionPair {

  private Optional<String> system;
  private Optional<String> version;

  /**
   * Prüft, ob das System und die Version vollständig definiert sind.
   *
   * @return true, wenn sowohl System als auch Version definiert sind, sonst false.
   */
  public boolean isFullyDefined() {
    return system.isPresent() && version.isPresent();
  }
}
